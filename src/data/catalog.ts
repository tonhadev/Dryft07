export function getCategory(slug?: string) {
  return CATEGORIES.find((c) => c.slug === slug);
}

export function getBrandsForCategory(slug: CategorySlug): Brand[] {
  // marcas declaradas para a categoria + qualquer marca que já tenha produto nela
  const fromBrands = BRANDS.filter((b) => b.categories.includes(slug));
  const fromProducts = PRODUCTS.filter((p) => p.category === slug && p.brand)
    .map((p) => BRANDS.find((b) => b.slug === p.brand))
    .filter((b): b is Brand => Boolean(b));
  const all = [...fromBrands, ...fromProducts];
  return all.filter((b, i) => all.findIndex((x) => x.slug === b.slug) === i);
}

export function getBrand(slug?: string) {
  return BRANDS.find((b) => b.slug === slug);
}

export function getProducts(categorySlug: CategorySlug, brandSlug?: string | null) {
  return PRODUCTS.filter(
    (p) => p.category === categorySlug && (!brandSlug || p.brand === brandSlug)
  );
}

export function getProductBySlug(slug?: string) {
  return PRODUCTS.find((p) => p.slug === slug);
}

export function getFeaturedProducts(limit = 4) {
  const featured = PRODUCTS.filter((p) => p.featured);
  return (featured.length ? featured : PRODUCTS).slice(0, limit);
}

export function productImages(product: CatalogProduct) {
  return [product.image, ...(product.images ?? [])];
}

export function formatBRL(value: number) {
  return new Intl.NumberFormat("pt-BR", {
    style: "currency",
    currency: "BRL",
  }).format(value);
}

export function categoryPath(slug: CategorySlug, brandSlug?: string) {
  return brandSlug ? `/categoria/${slug}?marca=${brandSlug}` : `/categoria/${slug}`;
}

export function productPath(product: CatalogProduct) {
  return `/produto/${product.slug}`;
}
