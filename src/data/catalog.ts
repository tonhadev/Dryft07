export type CategorySlug =
  | "camisas-street"
  | "camisas-oversize"
  | "shorts-basic"
  | "moletom-oversize";

export interface Category {
  slug: CategorySlug;
  name: string;
  /** Se true, a página da categoria mostra as abas de marcas */
  hasBrands: boolean;
  description: string;
  cover: string;
}

export interface Brand {
  /** identificador usado na URL, ex.: "marca-a" */
  slug: string;
  /** nome exibido — não é traduzido */
  name: string;
  /** categorias em que a marca aparece */
  categories: CategorySlug[];
}

export interface CatalogProduct {
  /** identificador único, usado na URL */
  slug: string;
  /** nome da peça — não é traduzido */
  name: string;
  /** código/referência interna */
  sku: string;
  category: CategorySlug;
  /** slug da marca (apenas para camisas street/oversize) */
  brand?: string;
  price: number;
  /** preço "de" opcional, para promoções */
  compareAtPrice?: number;
  /** produto cadastrado, aguardando definição de preço */
  pricePending?: boolean;
  /** imagem principal */
  image: string;
  /** imagens adicionais (a 1ª é usada no hover do card) */
  images?: string[];
  sizes?: string[];
  /** cores disponíveis; quando omitido, camisas usam a paleta padrão */
  colors?: string[];
  description: string;
  /** quantidade em estoque; 0 = esgotado */
  stock: number;
  /** destaque na página inicial */
  featured?: boolean;
  /** produto de exemplo/demonstração */
  demo?: boolean;
}

